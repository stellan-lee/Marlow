"""Regression coverage for browser tooling permissions in the image."""

from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
DOCKERFILE = REPO_ROOT / "Dockerfile"


def test_dockerfile_chowns_runtime_node_modules_to_marlow_user() -> None:
    text = DOCKERFILE.read_text()

    chown_lines = [
        line for line in text.splitlines()
        if "chown" in line and "marlow:marlow" in line
    ]
    assert chown_lines, (
        "Dockerfile must contain a chown -R marlow:marlow for the runtime "
        "node_modules trees; see #18800"
    )

    chown_block = "\n".join(chown_lines)

    # both runtime-mutable trees must be passed to the chown command.
    # /opt/marlow/web is intentionally excluded: it is build-time only,
    # because MARLOW_WEB_DIST points at marlow_cli/web_dist for runtime.
    for required_path in ("/opt/marlow/node_modules",):
        assert required_path in chown_block, (
            f"{required_path} must be passed to a chown -R marlow:marlow "
            f"command in the Dockerfile (see #18800)"
        )
